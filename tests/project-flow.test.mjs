import test from 'node:test';
import assert from 'node:assert/strict';
import {bootGeoTwin} from './support/dom.mjs';

test('portable project opens in an empty browser with geometries, sources, cone and geological results, settings and plans',async()=>{
  let app=await bootGeoTwin();
  try {
    app.click('showcase-run');
    await app.waitFor(()=>app.el('showcase-status').textContent.startsWith('Caso calculado'),'showcase');
    app.input('mission-observed',0);app.input('mission-notes','Plan portable con valor cero.');
    app.click('showcase-open');
    app.change('study-width',1);app.click('study-square');app.click('study-measure');
    await app.waitFor(()=>app.el('study-library').options.length>1,'saved base');
    const area=app.el('study-library').value;
    app.input('study-name','Base interpretada <img src=x onerror=alert(1)>');
    app.input('study-evidence-url','https://example.org/geology');
    app.input('study-justification','Contorno aportado para comprobar la exportación.');app.click('study-metadata-save');
    app.change('cone-earth-base',area);app.click('cone-run');
    await app.waitFor(()=>app.el('cone-status').textContent.startsWith('Medición terminada'),'individual measurement');
    assert.equal(app.el('cone-results').querySelectorAll('tbody tr').length,1);
    app.click('cone-export');
    const cone=JSON.parse(await app.downloads.at(-1).text());
    assert.equal(cone.measurements[0].id,area);
    assert.equal(cone.measurements[0].resolutionM,30);
    app.click('peru-geology-run');
    await app.waitFor(()=>app.el('peru-geology-status').textContent.startsWith('Intersección terminada'),'geological intersection');
    app.click('peru-geology-export');
    const geo=JSON.parse(await app.downloads.at(-1).text());
    assert.equal(geo.type,'FeatureCollection');
    assert.equal(geo.source.scale,'1:100 000');
    assert.ok(geo.measurement.coverage>.95 && geo.features.length>0);
    assert.ok(geo.features.every(f=>f.properties.OBJECTID && f.geometry.type==='MultiPolygon'));
    app.change('validation-case','andahua-ulysses');app.submit('validation-form');
    await app.waitFor(()=>!app.el('validation-exports').hidden,'validation');
    app.change('validation-width',5);app.change('validation-limit',20);app.change('validation-slope-margin',.3);
    app.input('validation-note','Escenario transportable.');
    app.input('scan-source','https://example.org/cartography');
    app.change('study-layer','peru-geology');
    app.click('project-export');
    const text=await app.downloads.at(-1).text(),file=JSON.parse(text);
    assert.equal(file.format,'geotwin-project');
    assert.equal(file.schemaVersion,1);
    assert.equal(file.state.library[0].evidenceUrl,'https://example.org/geology');
    assert.equal(file.state.cones.result.measurements[0].resolutionM,30);
    assert.equal(file.state.peruGeology.result.source.scale,'1:100 000');
    assert.ok(file.state.values.missionPlans.caseData.payload.regionalGeology);
    assert.deepEqual(app.errors,[]);
    await app.close();app=await bootGeoTwin();
    assert.deepEqual(app.storage(),{});
    app.file('project-import',text);
    await app.waitFor(()=>app.el('study-save-status').textContent.startsWith('Proyecto abierto'),'portable import');
    assert.equal(app.el('mission-observed').value,'0');
    assert.equal(app.el('mission-notes').value,'Plan portable con valor cero.');
    assert.equal(app.el('scan-source').value,'https://example.org/cartography');
    assert.equal(app.el('study-evidence-url').value,'https://example.org/geology');
    assert.equal(app.el('validation-width').value,'5');assert.equal(app.el('validation-limit').value,'20');
    assert.equal(app.el('validation-slope-margin').value,'0.3');
    assert.equal(app.el('validation-note').value,'Escenario transportable.');
    assert.equal(app.el('study-layer').value,'peru-geology');
    assert.equal(app.el('cone-earth-base').value,area);
    assert.equal(app.el('cone-results').querySelectorAll('tbody tr').length,1);
    assert.ok(app.el('peru-geology-results').querySelectorAll('tbody tr').length>3);
    assert.equal(app.el('showcase-results').querySelectorAll('tbody tr').length,5);
    assert.equal(app.document.querySelector('img[src="x"]'),null);
    app.click('validation-export-json');
    const scenario=JSON.parse(await app.downloads.at(-1).text());
    assert.equal(scenario.parameters.windowKm,5);assert.equal(scenario.parameters.slopeLimitDeg,20);
    app.file('project-import','{"format":"wrong"}');
    await app.waitFor(()=>app.el('study-save-status').textContent.startsWith('No se pudo abrir'),'invalid project');
    assert.equal(app.el('mission-observed').value,'0');
    assert.equal(app.el('cone-results').querySelectorAll('tbody tr').length,1);
    const broken=JSON.parse(text);broken.state.values.areaState.Earth.point.lat='bad';
    app.file('project-import',JSON.stringify(broken));
    await app.waitFor(()=>app.el('study-save-status').textContent.includes('Ubicación'),'invalid point');
    assert.equal(app.el('cone-earth-base').value,area);
    await app.settle();assert.deepEqual(app.errors,[]);
  } finally {await app.close();}
});

test('portable project preserves an unmeasured draft and rejects unsafe sources before replacing it',async()=>{
  let app=await bootGeoTwin();
  try {
    app.click('showcase-open');app.change('study-width',2);app.click('study-square');app.click('project-export');
    const text=await app.downloads.at(-1).text(),saved=JSON.parse(text);
    assert.equal(saved.state.library.length,0);
    assert.equal(saved.state.drafts.at(-1)[1].points.length,4);
    await app.close();app=await bootGeoTwin();app.file('project-import',text);
    await app.waitFor(()=>app.el('study-save-status').textContent.startsWith('Proyecto abierto'),'draft import');
    assert.equal(app.el('study-width').value,'2');
    assert.equal(app.el('study-measure').disabled,false);
    assert.equal(app.el('study-clear').disabled,false);
    const unsafe=JSON.parse(text);unsafe.state.editor.documented={name:'bad',url:'javascript:alert(1)'};
    app.file('project-import',JSON.stringify(unsafe));
    await app.waitFor(()=>app.el('study-save-status').textContent.includes('HTTP'),'unsafe source');
    assert.equal(app.el('study-width').value,'2');
    assert.equal(app.el('study-measure').disabled,false);
    await app.settle();assert.deepEqual(app.errors,[]);
  } finally {await app.close();}
});
