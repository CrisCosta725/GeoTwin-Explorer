import fs from 'node:fs/promises';
import {fromFile} from 'geotiff';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {analogs} from '../dist/assets/analogs.js';

// NASADEM HGT v001, NASA JPL. Public COG delivery via Planetary Computer.
// Downloads are build-time only: no login, token or remote dependency in the app.
const cache=new URL('../.cache/nasadem/',import.meta.url);
await fs.mkdir(cache,{recursive:true});
const profiles={},failures=[];
const size=320,spanKm=10;
async function download(url,file){
 try{await fs.access(file);return;}catch{}
 const response=await fetch(url,{signal:AbortSignal.timeout(60000)});
 if(!response.ok)throw Error(`${response.status}: ${url}`);
 await fs.writeFile(file,new Uint8Array(await response.arrayBuffer()));
}
for(const site of analogs){
 if(site.lat < -56 || site.lat >= 60){profiles[site.id]={unavailable:'outside-coverage'};continue;}
 try{
  const dy=spanKm/2/111.195,dx=dy/Math.cos(site.lat*Math.PI/180);
  const bbox=[site.lon-dx,site.lat-dy,site.lon+dx,site.lat+dy];
  const heights=new Float64Array(size*size).fill(NaN),sources=[];
  for(let lat=Math.floor(bbox[1]);lat<=Math.floor(bbox[3]);lat++)for(let lon=Math.floor(bbox[0]);lon<=Math.floor(bbox[2]);lon++){
   const tile=(lat<0?'s':'n')+String(Math.abs(lat)).padStart(2,'0')+(lon<0?'w':'e')+String(Math.abs(lon)).padStart(3,'0');
   const item='NASADEM_HGT_'+tile;
   const url=`https://planetarycomputer.microsoft.com/api/data/v1/item/bbox/${bbox.join(',')}.tif?collection=nasadem&item=${item}&assets=elevation&width=${size}&height=${size}&resampling=bilinear`;
   const file=new URL(`${site.id}-${tile}.tif`,cache);
   await download(url,file);
   const tiff=await fromFile(fileURLToPath(file));
   try{
    const image=await tiff.getImage(),r=await image.readRasters();
    if(image.getWidth()!==size||image.getHeight()!==size||r.length<2)throw Error('Unexpected raster shape or missing validity mask');
    for(let p=0;p<heights.length;p++)if(r[1][p]>0&&r[0][p]!==-32768)heights[p]=r[0][p];
   }finally{await tiff.close();}
   sources.push({item,url,sha256:createHash('sha256').update(await fs.readFile(file)).digest('hex')});
  }
  const sample=(x,y)=>{const z=heights[y*size+x];return Number.isFinite(z)?Math.round(z):null;};
  const mean=(a,b)=>a===null||b===null?null:Math.round((a+b)/2);
  const EW=[],SN=[];
  for(let i=0;i<size;i++){
   const distanceKm=+(spanKm*(i+.5)/size).toFixed(5);
   EW.push({distanceKm,elevationM:mean(sample(i,size/2-1),sample(i,size/2))});
   SN.push({distanceKm,elevationM:mean(sample(size/2-1,size-1-i),sample(size/2,size-1-i))});
  }
  if([...EW,...SN].some(p=>p.elevationM===null))throw Error('Incomplete transects; refusing to publish missing elevations');
  profiles[site.id]={center:[site.lat,site.lon],spanKm,stepKm:spanKm/size,resolutionM:30,EW,SN,sources};
  console.log(`${site.id}: two NASADEM transects, ${size} samples each`);
 }catch(error){failures.push(site.id);console.error(`${site.id}: ${error.message}`);}
}
if(failures.length)throw Error('Incomplete build: '+failures.join(', '));
await fs.writeFile(new URL('../dist/assets/earth-profiles.js',import.meta.url),'// NASADEM HGT v001; generated by scripts/build-earth-profiles.mjs\nexport const earthProfiles='+JSON.stringify(profiles)+';\n');
